package app.planner.ui

import androidx.compose.foundation.horizontalScroll
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.rememberScrollState
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.runtime.saveable.rememberSaveable
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import app.planner.model.Task
import app.planner.model.TaskStatus
import java.time.LocalDate
import java.time.ZoneId

@Composable
fun TasksScreen(tasksVm: TasksViewModel, planVm: PlanViewModel, onEdit: (Task) -> Unit, onAdd: () -> Unit, onLogProgress: (Task) -> Unit, onOpenTemplate: () -> Unit) {
    val zone = ZoneId.systemDefault()
    val tasks by tasksVm.all.collectAsStateWithLifecycle()
    val today by planVm.todayTasks.collectAsStateWithLifecycle()
    val allDay by planVm.todayAllDay.collectAsStateWithLifecycle()
    val blocks by planVm.scheduledBlocks.collectAsStateWithLifecycle()
    val template by tasksVm.template.collectAsStateWithLifecycle()
    val generated by tasksVm.generated.collectAsStateWithLifecycle()
    var filter by rememberSaveable { mutableStateOf("Today") }
    DisposableEffect(Unit) { onDispose { tasksVm.clearGenerated() } }
    val byTask = blocks.associateBy { it.taskId }
    val list = when (filter) {
        "Today" -> today
        "Done" -> tasks.filter { it.status == TaskStatus.DONE }
        "Unplanned" -> tasks.filter { it.status != TaskStatus.DONE && it.id !in byTask }
        "Due soon" -> tasks.filter { it.status != TaskStatus.DONE && it.dueAt?.atZone(zone)?.toLocalDate()?.let { due -> due <= LocalDate.now(zone).plusDays(2) } == true }
        else -> tasks.filter { it.status != TaskStatus.DONE }
    }
    LazyColumn(
        modifier = Modifier.fillMaxSize().padding(horizontal = 22.dp),
        contentPadding = PaddingValues(bottom = 24.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        item { ScreenHeading("Off your mind, into your day", "Things to do") }
        item {
            Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("Today", "All", "Due soon", "Unplanned", "Done").forEach { label ->
                    FilterChip(selected = filter == label, onClick = { filter = label }, label = { Text(label) })
                }
            }
        }
        if (tasks.isEmpty()) item {
            EmptyTasksCard(today = false, templateItems = template.items.size, message = generated, onAdd = onAdd, onGenerate = { tasksVm.generateWeek(0) }, onSetUpTemplate = onOpenTemplate)
        } else if (list.isEmpty() && (filter != "Today" || allDay.isEmpty())) item {
            PlannerPanel { Text("You’re all clear.", style = MaterialTheme.typography.titleMedium); Text("No tasks in this view.", color = MaterialTheme.colorScheme.onSurfaceVariant) }
        }
        if (filter == "Today") items(allDay, key = { it.key }) { task -> AllDayTaskRow(task, onToggle = { planVm.toggleAllDay(task) }) }
        items(list, key = { it.id }) { task ->
            TaskRow(task, zone, byTask[task.id], onToggle = { tasksVm.toggleDone(task) }, onClick = { onEdit(task) }, onLongClick = { onLogProgress(task) })
        }
        item { Button(onClick = onAdd, modifier = Modifier.fillMaxWidth()) { Text("Add a task") } }
        item { TextButton(onClick = onOpenTemplate) { Text("Weekly template · Make recurring work take care of itself") } }
    }
}
